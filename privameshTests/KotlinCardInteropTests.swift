//
//  KotlinCardInteropTests.swift
//  privameshTests
//
//  A contact card made by the desktop and Android clients, opened here.
//
//  This is the direction that was never checked. Both sides claim to speak the
//  same format, and when they do not the symptom is "the QR does not scan" and
//  "the link does nothing" - with nothing to point at. The vector is written by
//  `KotlinCardExportTest` in the shared core and committed alongside the app.
//

import Testing
import Foundation
@testable import privamesh

@Suite("Cards from the other clients")
struct KotlinCardInteropTests {

    private struct KotlinCard: Decodable {
        let address: String
        let bundleBase64: String
        let qrPayload: String
        let inviteLinkWeb: String
        let inviteLinkApp: String
        let nickname: String
    }

    /// Read from the source tree rather than the test bundle.
    ///
    /// The vector is committed next to this file and regenerated by the shared
    /// core; adding it as a bundle resource would mean an Xcode project change
    /// every time the fixtures move.
    private func vector() throws -> KotlinCard {
        let url = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .appendingPathComponent("vectors/kotlin_contact_card.json")
        let data = try #require(
            try? Data(contentsOf: url),
            "missing \(url.path) - regenerate it with ./gradlew :core-crypto:test -PcardOut=...",
        )
        return try JSONDecoder().decode(KotlinCard.self, from: data)
    }

    /// The QR a desktop draws has to be a card this app can read.
    @Test func aQrFromTheDesktopParses() throws {
        let vector = try vector()
        let card = try #require(ContactCard.fromQRPayload(vector.qrPayload),
                                "the desktop QR payload did not parse")

        #expect(card.address == vector.address)
        #expect(card.hasValidAddress)

        // Compared field by field rather than as strings: Swift's JSONEncoder does
        // not fix key order, so the same bundle is a different base64 on each side
        // while being the same keys.
        let theirs = try PrekeyBundle.fromBase64(card.bundle)
        let mine = try PrekeyBundle.fromBase64(vector.bundleBase64)
        #expect(theirs.signingIdentityKey == mine.signingIdentityKey)
        #expect(theirs.dhIdentityKey == mine.dhIdentityKey)
        #expect(theirs.signedPrekeyPublic == mine.signedPrekeyPublic)
    }

    /// And the name it carries: a handle is meant to be the same on every client.
    @Test func theProfileSurvives() throws {
        let vector = try vector()
        let card = try #require(ContactCard.fromQRPayload(vector.qrPayload))
        #expect(card.profile?.nickname == vector.nickname)
    }

    /// Both link forms, since a desktop hands out the web one and the page turns
    /// it into the app one.
    @Test func bothLinkFormsOpen() throws {
        let vector = try vector()

        for link in [vector.inviteLinkWeb, vector.inviteLinkApp] {
            let url = try #require(URL(string: link), "not a URL: \(link)")
            let card = try #require(InviteLink.card(from: url), "did not parse: \(link)")
            #expect(card.address == vector.address)
        }
    }

    /// The inbox is what an opened link actually goes through.
    @Test func theInviteInboxAcceptsIt() async throws {
        let vector = try vector()
        let url = try #require(URL(string: vector.inviteLinkWeb))

        let inbox = await InviteInbox()
        let accepted = await inbox.accept(url)
        #expect(accepted, "the invite inbox refused a desktop link")

        let payload = await inbox.take()
        #expect(payload != nil)
    }
}
